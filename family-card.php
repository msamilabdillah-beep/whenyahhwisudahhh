<script>

document.addEventListener("DOMContentLoaded", function () {

    const checklistInputs = document.querySelectorAll(".checklist-input");

    const percentageElement = document.getElementById("progressPercentage");

    const progressBar = document.getElementById("readinessProgressBar");

    const progressCount = document.getElementById("progressCount");

    const completeCount = document.getElementById("completeCount");

    const incompleteCount = document.getElementById("incompleteCount");

    const progressMessage = document.getElementById("progressMessage");

    if (!percentageElement || !progressBar || !progressCount ||
        !completeCount || !incompleteCount || !progressMessage) {
        return;
    }

    function updateReadinessProgress() {

        const total = checklistInputs.length;

        let completed = 0;


        checklistInputs.forEach(function (input) {

            const status = document.querySelector(
                '[data-status="' + input.name + '"]'
            );


            if (input.checked) {

                completed++;

                if (status) {

                    status.textContent = "● Lengkap";

                    status.classList.remove("status-incomplete");

                    status.classList.add("status-complete");

                }

            } else {

                if (status) {

                    status.textContent = "● Belum lengkap";

                    status.classList.remove("status-complete");

                    status.classList.add("status-incomplete");

                }

            }

        });


        // Formula: (completed / 5) x 100

        const percentage = total > 0
            ? Math.round((completed / total) * 100)
            : 0;

        const incomplete = total - completed;


        // Update percentage

        percentageElement.textContent = percentage + "%";


        // Update progress bar

        progressBar.style.width = percentage + "%";

        progressBar.setAttribute("aria-valuenow", percentage);


        // Update counts

        progressCount.textContent = completed + " dari " + total;

        completeCount.textContent = completed;

        incompleteCount.textContent = incomplete;


        // Update message

        if (percentage === 100) {

            progressMessage.textContent =
                "Seluruh indikator checklist telah dilengkapi.";

        } else if (percentage === 0) {

            progressMessage.textContent =
                "Belum ada indikator checklist yang dilengkapi.";

        } else {

            progressMessage.textContent =
                "Masih terdapat " + incomplete +
                " indikator yang perlu dilengkapi.";

        }

    }


    // Update progress whenever a checkbox changes

    checklistInputs.forEach(function (input) {

        input.addEventListener("change", updateReadinessProgress);

    });


    // Initial calculation

    updateReadinessProgress();


    // Frontend validation

    const checklistForm = document.getElementById("checklistForm");

    if (checklistForm) {
        checklistForm.addEventListener("submit", function (event) {

        const familyCode = document.getElementById("family_code").value.trim();

        if (!familyCode) {

            event.preventDefault();

            alert("Kode keluarga wajib diisi.");

            return;

        }

        // Backend handles the actual database update.

        });
    }

});

</script>

