    // Match the family-code format generated by family_save.php.
    if (!preg_match('/^SK-\\d{4}-\\d{5}$/D', $familyCode)) {
        $lookupError = 'Format kode keluarga tidak valid. Periksa kembali kode pada kartu Anda.';
    } else {
        try {
            $stmt = $conn->prepare(
                "SELECT
                    f.id,
                    f.family_code,
                    f.family_name,
                    f.neighborhood,
                    f.member_count,
                    f.created_at,
                    rc.id AS checklist_id,
                    rc.emergency_bag,
                    rc.emergency_contacts,
                    rc.first_aid_kit,
                    rc.important_documents,
                    rc.assembly_point
                FROM families f
                LEFT JOIN readiness_checklists rc
                    ON rc.family_id = f.id
                WHERE f.family_code = ?
                LIMIT 1"
            );

            $stmt->bind_param('s', $familyCode);
            $stmt->execute();
            $stmt->bind_result(
                $dbFamilyId,
                $dbFamilyCode,
                $dbFamilyName,
                $dbNeighborhood,
                $dbMemberCount,
                $dbCreatedAt,
                $dbChecklistId,
                $dbEmergencyBag,
                $dbEmergencyContacts,
                $dbFirstAidKit,
                $dbImportantDocuments,
                $dbAssemblyPoint
            );

            if ($stmt->fetch()) {
                $family = [
                    'id' => (int) $dbFamilyId,
                    'family_code' => (string) $dbFamilyCode,
                    'family_name' => (string) $dbFamilyName,
                    'neighborhood' => (string) $dbNeighborhood,
                    'member_count' => (int) $dbMemberCount,
                    'created_at' => (string) $dbCreatedAt,
                ];

                $hasChecklist = $dbChecklistId !== null;

                if ($hasChecklist) {
                    $checklist = [
                        'emergency_bag' => (int) $dbEmergencyBag,
                        'emergency_contacts' => (int) $dbEmergencyContacts,
                        'first_aid_kit' => (int) $dbFirstAidKit,
                        'important_documents' => (int) $dbImportantDocuments,
                        'assembly_point' => (int) $dbAssemblyPoint,
                    ];
                }
            }

            $stmt->close();

            if ($family === null) {
                $lookupError = 'Kartu keluarga tidak ditemukan. Pastikan kode keluarga yang Anda masukkan benar.';
            } elseif (!$hasChecklist) {
                $lookupError = 'Data keluarga ditemukan, tetapi checklist belum tersedia. Hubungi koordinator untuk pemeriksaan data.';
            }
        } catch (Throwable $e) {
            error_log('[SIAGAKAMPUNG FAMILY CARD ERROR] ' . $e->getMessage());
            http_response_code(500);
            $lookupError = 'Data kartu keluarga belum dapat dimuat. Silakan coba kembali beberapa saat lagi.';
        }
    }
}

